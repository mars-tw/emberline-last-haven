"""Move regression consumers to this round; preserve exact historical test inputs."""
from pathlib import Path
import subprocess,json,hashlib,shutil
root=Path.cwd().resolve();assert root.name=='apocalypse-anthology'
target=root/'docs/content/r15';target.mkdir(parents=True,exist_ok=True)
mapping=lambda s:s.replace('docs/content/r14/regression','docs/content/r15/regression').replace('docs/content/r14','docs/content/r15/regression/r14')
tracked=subprocess.check_output(['git','-c','core.quotepath=false','ls-files','-z']).decode('utf-8').split('\0')
records=[]
for name in tracked:
 if not name.startswith('docs/content/r14/') or name.endswith('.md'):continue
 source=(root/name).resolve();dest=(root/mapping(name)).resolve()
 assert source.is_relative_to(root/'docs/content/r14') and dest.is_relative_to(target/'regression')
 if not source.is_file():continue
 dest.parent.mkdir(parents=True,exist_ok=True)
 if not dest.exists():shutil.copyfile(source,dest)
 if source.suffix=='.json':
  data=dest.read_text(encoding='utf-8-sig');dest.write_text(mapping(data),encoding='utf-8',newline='\n')
 records.append(dict(source=name,target=dest.relative_to(root).as_posix(),bytes=source.stat().st_size,sha256=hashlib.sha256(source.read_bytes()).hexdigest(),reason='Regression input/output contract; historical before images remain exact bytes, current gameplay images regenerated by full check'))
for folder in ['scripts','tests']:
 for p in (root/folder).rglob('*'):
  if p.suffix not in ['.mjs','.ts','.py','.ps1'] or 'content-r15' in p.name:continue
  data=p.read_text(encoding='utf-8-sig');updated=mapping(data)
  if data!=updated:p.write_text(updated,encoding='utf-8',newline='\n')
for folder in ['docs/evidence','docs/art','docs/store']:
 for p in (root/folder).rglob('*.json'):
  if 'cleanup' in p.name:continue
  data=p.read_text(encoding='utf-8-sig');updated=mapping(data)
  if data!=updated:p.write_text(updated,encoding='utf-8',newline='\n')
(target/'regression-migration.json').write_text(json.dumps(dict(status='EXECUTED',records=records,mediaFiles=sum(Path(r['source']).suffix.lower() in ['.png','.webp','.jpg','.mp4','.webm'] for r in records),reason='Original tracked media may now be deleted after hash-bound inventory; do not delete untracked files'),ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(json.dumps(dict(status='EXECUTED',migrated=len(records))))
